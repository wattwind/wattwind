"""Write docs/img/ride-chart.svg: an interval workout run through the fan's own Auto code (firmware/fan_logic.py).

The chart is not drawn by hand: a simulated rider's power, heart rate and cadence go second by second into
FanLogic.update(), exactly as on the fan, and the level it returns is plotted. Run it again after changing
fan_logic.py or the default thresholds:  python tools/make_ride_chart.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "firmware"))
import config      # noqa: E402  (firmware modules: pure Python)
import fan_logic   # noqa: E402

DST = os.path.join(HERE, "..", "docs", "img", "ride-chart.svg")
FTP = 240

# (minutes, watts at the start, watts at the end, label); 0 W = not pedaling
PLAN = [(10, 100, 180, "warm-up")]
for _ in range(4):
    PLAN += [(4, 275, 275, "interval"), (3, 125, 125, "recovery")]
PLAN += [(8, 160, 110, "cool-down"), (6, 0, 0, "stop")]


def ride():
    """Second-by-second (t, power, cadence, hr) of the plan; heart rate follows power with a lag and slow drift."""
    out, t, hr = [], 0, 75.0
    for minutes, w0, w1, _ in PLAN:
        n = minutes * 60
        for i in range(n):
            p = w0 + (w1 - w0) * i / n
            target = 72 + 0.36 * p + t / 600.0 if p else 85
            hr += (target - hr) / (25.0 if target > hr else 45.0)
            out.append((t, round(p), 88 if p else 0, round(hr)))
            t += 1
    return out


def main():
    cfg = dict(config.DEFAULTS, ftp=FTP)
    logic = fan_logic.FanLogic(cfg)
    data = [(t, p, hr, logic.update(t, p, c, hr)) for t, p, c, hr in ride()]
    T = data[-1][0] + 1

    W, H = 1000, 400
    x0, x1 = 60, 935
    py0, py1 = 40, 230           # power plot (top, bottom)
    ly0, ly1 = 262, 342          # level band
    PMAX = 350
    X = lambda t: x0 + (x1 - x0) * t / T
    PY = lambda w: py1 - (py1 - py0) * w / PMAX
    LY = lambda lv: ly1 - (ly1 - ly0) * lv / 3

    pw = " ".join("%.1f,%.1f" % (X(t), PY(p)) for t, p, _, _ in data[::5])
    hrl = " ".join("%.1f,%.1f" % (X(t), PY((h - 40) * 2)) for t, _, h, _ in data[::5])
    lv, pts = None, []
    for t, _, _, level in data:
        if level != lv:
            if lv is not None:
                pts.append("%.1f,%.1f" % (X(t), LY(lv)))
            pts.append("%.1f,%.1f" % (X(t), LY(level)))
            lv = level
    pts.append("%.1f,%.1f" % (X(T), LY(lv)))
    area = "%.1f,%.1f " % (X(0), LY(0)) + " ".join(pts) + " %.1f,%.1f" % (X(T), LY(0))

    s = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" '
         'font-family="Segoe UI, system-ui, Arial, sans-serif" font-size="13" role="img" aria-label="An interval '
         'workout and the fan level Auto picks: off in the first minutes of the warm-up, level 1 then 2 as it builds, '
         'level 3 in each hard interval, down to 2 then 1 in the recoveries, stepping down in the cool-down and off after '
         'pedaling stops">' % (W, H, W, H),
         '<!-- generated by tools/make_ride_chart.py from firmware/fan_logic.py: run it again, do not edit -->',
         '<rect x="1" y="1" width="%d" height="%d" rx="14" fill="#fff" stroke="#d6dad2" stroke-width="1.5"/>' % (W - 2, H - 2)]
    # phase bands and labels
    t = 0
    for minutes, _, _, label in PLAN:
        if label == "interval":
            s.append('<rect x="%.1f" y="%d" width="%.1f" height="%d" fill="#fdecea"/>' % (X(t), py0, X(t + minutes * 60) - X(t), ly1 - py0))
        t += minutes * 60
    marks = [(5 * 60, "warm-up"), (10 * 60 + 14 * 60, "4 × 4 min hard, 3 min easy"), (38 * 60 + 4 * 60, "cool-down"), (46 * 60 + 3 * 60, "stopped")]
    for tm, label in marks:
        s.append('<text x="%.1f" y="%d" text-anchor="middle" fill="#5a6068">%s</text>' % (X(tm), py0 - 12, label))
    # power axis
    for w in (100, 200, 300):
        s.append('<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" stroke="#eceee9"/>' % (x0, PY(w), x1, PY(w)))
        s.append('<text x="%d" y="%.1f" text-anchor="end" fill="#5a6068">%d W</text>' % (x0 - 6, PY(w) + 4, w))
    s.append('<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" stroke="#d62828" stroke-dasharray="5 4"/>' % (x0, PY(FTP), x1, PY(FTP)))
    s.append('<text x="%d" y="%.1f" fill="#d62828">FTP %d W</text>' % (x0 + 4, PY(FTP) - 5, FTP))
    for bpm in (90, 140, 190):
        s.append('<text x="%d" y="%.1f" fill="#d62828" fill-opacity=".8">%d bpm</text>' % (x1 + 6, PY((bpm - 40) * 2) + 4, bpm))
    s.append('<polyline points="%s" fill="none" stroke="#d62828" stroke-width="1.6" stroke-opacity=".55"/>' % hrl)
    s.append('<polyline points="%s" fill="none" stroke="#1f6feb" stroke-width="2.2"/>' % pw)
    # level band
    for lvl, name in ((0, "Off"), (1, "1"), (2, "2"), (3, "3")):
        s.append('<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" stroke="#eceee9"/>' % (x0, LY(lvl), x1, LY(lvl)))
        s.append('<text x="%d" y="%.1f" text-anchor="end" fill="#5a6068">%s</text>' % (x0 - 6, LY(lvl) + 4, name))
    s.append('<polygon points="%s" fill="#dcefe4" stroke="#1f7a4d" stroke-width="2.2" stroke-linejoin="round"/>' % area)
    s.append('<text x="%d" y="%d" fill="#1b1d21" font-weight="600">Fan level</text>' % (x0, ly0 - 10))
    for m in range(0, T // 60 + 1, 10):
        s.append('<text x="%.1f" y="%d" text-anchor="middle" fill="#5a6068">%d min</text>' % (X(m * 60), ly1 + 18, m))
    # legend
    lx = x0
    for color, op, label in (("#1f6feb", 1, "power"), ("#d62828", .55, "heart rate"), ("#1f7a4d", 1, "fan level chosen by Auto")):
        s.append('<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="%s" stroke-opacity="%s" stroke-width="3"/>' % (lx, H - 14, lx + 22, H - 14, color, op))
        s.append('<text x="%d" y="%d" fill="#1b1d21">%s</text>' % (lx + 28, H - 10, label))
        lx += 60 + 8 * len(label)
    s.append('<text x="%d" y="%d" text-anchor="end" fill="#5a6068">the fan\'s own Auto code, default settings, FTP %d W</text>' % (x1, H - 10, FTP))
    s.append("</svg>")
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(s) + "\n")
    changes = sum(1 for a, b in zip(data, data[1:]) if a[3] != b[3])
    print("docs/img/ride-chart.svg written: %d min, %d level changes, max HR %d" % (T // 60, changes, max(d[2] for d in data)))


if __name__ == "__main__":
    main()
